"""public/data/sites.json: which sites exist, and whether each data file is real or a placeholder.

Standard library only. The status of a file is read from the file itself:
  - a JSON object with "placeholder": true            -> "placeholder"
  - a JSON list whose entries carry "placeholder": true -> "placeholder" (sources.json is a list in §4)
  - any other existing file                            -> "real"
  - missing                                            -> "missing"
So a notebook that writes a real file (without the placeholder flag) flips its status automatically
the next time the index is rebuilt.
"""

import json

from . import config

# The handoff §4 data contract, per site folder. PNG frames are covered by frames/manifest.json.
CONTRACT_FILES = [
    "summary.json",
    "dunes.geojson",
    "dunes_2000.geojson",
    "vectors.geojson",
    "targets.geojson",
    "wind_summary.json",
    "sources.json",
    "frames/manifest.json",
]


def file_status(path):
    if not path.exists():
        return "missing"
    try:
        obj = json.loads(path.read_text())
    except (ValueError, UnicodeDecodeError):
        return "real"
    if isinstance(obj, dict) and obj.get("placeholder") is True:
        return "placeholder"
    if isinstance(obj, list) and any(isinstance(e, dict) and e.get("placeholder") is True for e in obj):
        return "placeholder"
    return "real"


def site_status(files):
    vals = set(files.values())
    if not files or vals == {"missing"}:
        return "no_data"
    if vals == {"real"}:
        return "real"
    if vals <= {"placeholder", "missing"}:
        return "placeholder"
    return "partial"


def build_index():
    sites = []
    for s in config.load_sites():
        entry = {"id": s["id"], "name": s["name"], "bbox": s["bbox"], "verified": bool(s.get("verified"))}
        folder = config.public_dir(s["id"])
        if s.get("verified") and folder.is_dir():
            files = {f: file_status(folder / f) for f in CONTRACT_FILES}
            entry["status"] = site_status(files)
            entry["data_dir"] = f"{s['id']}/"
            entry["files"] = files
        else:
            entry["status"] = "not_located" if not s.get("verified") else "no_data"
            entry["data_dir"] = None
            entry["files"] = {}
        sites.append(entry)
    default = next((e["id"] for e in sites if e["data_dir"]), None)
    return {
        "note": (
            "Index of DuneSight sites, generated by pipeline/dunesight/site_index.py from pipeline/sites.json. "
            "Each site with data has the full handoff §4 file set under data/<id>/ (formats unchanged). "
            "status: 'real' = every file is a pipeline result; 'partial' = some real, some placeholder "
            "(see 'files'); 'placeholder' = all fake; 'not_located' = box not verified yet, no data. "
            "Placeholder files also carry \"placeholder\": true inside them."
        ),
        "default_site": default,
        "sites": sites,
    }


def write_index():
    config.PUBLIC_DATA.mkdir(parents=True, exist_ok=True)
    idx = build_index()
    (config.PUBLIC_DATA / "sites.json").write_text(json.dumps(idx, indent=1) + "\n")
    return idx
