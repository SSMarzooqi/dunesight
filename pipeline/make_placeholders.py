"""Generate PLACEHOLDER versions of every data-contract file (handoff.md §4) into public/data/.

WHAT THIS DOES:
    Reads the AOI from pipeline/aoi.json and writes fake-but-plausible data so the app can be
    built before the real pipeline runs. Every file is marked as placeholder ("placeholder": true
    where the format allows it, "PLACEHOLDER" in scene IDs and notes). Nothing here is a result.

Deterministic (fixed seed). Uses only the Python standard library, so it runs with or without the venv:
    python3 pipeline/make_placeholders.py        (or: npm run placeholders)
"""

import json
import math
import random
import struct
import zlib
from pathlib import Path

SEED = 20260514
ROOT = Path(__file__).resolve().parent.parent
AOI_PATH = ROOT / "pipeline" / "aoi.json"
OUT = ROOT / "public" / "data"
FRAMES = OUT / "frames"

PLACEHOLDER_NOTE = (
    "PLACEHOLDER: fake values generated by pipeline/make_placeholders.py for app development. "
    "Not a measurement. Replaced by the pipeline notebooks."
)

RDD_DEG = 132.0          # fake resultant drift direction (downwind of a NW shamal -> SE)
BASE_YEAR = 2025
DUNES_START_YEAR = 2000
PROJECTION_END = 2050    # threat window
HORIZON = 2100           # reach years beyond this are null
CLASS_CUTS = (1.0, 3.0, 8.0)  # stable < 1 <= slow < 3 <= active < 8 <= fast (m/yr), §3 Step 5 placeholders


# ---------- geometry helpers (local equirectangular metres around the AOI centre) ----------

class Local:
    def __init__(self, bbox):
        self.lon0 = (bbox["west"] + bbox["east"]) / 2
        self.lat0 = (bbox["south"] + bbox["north"]) / 2
        self.mx = 111_320.0 * math.cos(math.radians(self.lat0))
        self.my = 110_574.0

    def to_xy(self, lon, lat):
        return (lon - self.lon0) * self.mx, (lat - self.lat0) * self.my

    def to_ll(self, x, y):
        return round(self.lon0 + x / self.mx, 6), round(self.lat0 + y / self.my, 6)


def heading_vec(deg):
    """Unit vector (east, north) for a compass heading (0 = N, clockwise)."""
    r = math.radians(deg)
    return math.sin(r), math.cos(r)


def ellipse_ring(cx, cy, a, b, rot_deg, n=20):
    """Closed ring of an ellipse; a = half-length along heading, b = half-width."""
    ux, uy = heading_vec(rot_deg)
    vx, vy = uy, -ux
    pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        # slightly flattened on the downwind side to hint at a slip face
        along = a * math.cos(t) * (0.8 if math.cos(t) > 0 else 1.0)
        across = b * math.sin(t)
        pts.append((cx + along * ux + across * vx, cy + along * uy + across * vy))
    pts.append(pts[0])
    return pts


def point_in_poly(x, y, ring):
    inside = False
    for i in range(len(ring) - 1):
        x1, y1 = ring[i]
        x2, y2 = ring[i + 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            inside = not inside
    return inside


def dist_to_segment(x, y, a, b):
    (x1, y1), (x2, y2) = a, b
    dx, dy = x2 - x1, y2 - y1
    t = max(0.0, min(1.0, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - (x1 + t * dx), y - (y1 + t * dy))


def ang_diff(a, b):
    d = abs(a - b) % 360
    return min(d, 360 - d)


# ---------- tiny PNG writer (RGBA, stdlib only) ----------

def write_png(path, w, h, pixel):
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            raw.extend(pixel(x, y))

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def frame_pixel(rgb, alpha):
    def px(x, y, n=64):
        edge = x in (0, n - 1) or y in (0, n - 1)
        diag = (x + y) % 16 == 0
        if edge:
            return (*rgb, alpha)
        if diag:
            return (*rgb, alpha // 3)
        return (0, 0, 0, 0)
    return px


# ---------- builders ----------

def make_targets(local, bbox):
    """A fake road along the east side, a fake road along the south, and three fake farms SE of centre."""
    w, s, e, n = bbox["west"], bbox["south"], bbox["east"], bbox["north"]
    lon_road = e - 0.15 * (e - w)
    lat_road = s + 0.12 * (n - s)
    targets = []
    road_e = [(lon_road, s), (lon_road + 0.002, (s + n) / 2), (lon_road - 0.001, n)]
    road_s = [(w, lat_road), ((w + e) / 2, lat_road + 0.001), (e, lat_road - 0.0005)]
    targets.append(("T01", "PLACEHOLDER road A segment 1", "road", "LineString", road_e))
    targets.append(("T02", "PLACEHOLDER road B segment 1", "road", "LineString", road_s))
    farms = [
        (0.70, 0.30, 350, 250, "T03"),
        (0.78, 0.55, 300, 300, "T04"),
        (0.50, 0.20, 400, 200, "T05"),
    ]
    for fx, fy, hw, hh, tid in farms:
        cx, cy = local.to_xy(w + fx * (e - w), s + fy * (n - s))
        ring = [(cx - hw, cy - hh), (cx + hw, cy - hh), (cx + hw, cy + hh), (cx - hw, cy + hh), (cx - hw, cy - hh)]
        targets.append((tid, f"PLACEHOLDER farm {tid[1:]}", "farm", "Polygon", [local.to_ll(*p) for p in ring]))
    targets.append(("T06", "PLACEHOLDER building 1", "building", "Polygon",
                    [local.to_ll(*p) for p in (lambda c: [(c[0]-40, c[1]-40), (c[0]+40, c[1]-40), (c[0]+40, c[1]+40), (c[0]-40, c[1]+40), (c[0]-40, c[1]-40)])(local.to_xy(w + 0.62 * (e - w), s + 0.42 * (n - s)))]))
    return targets


def target_hit(local, targets, x, y):
    """Return the target id hit by point (x, y) in local metres, or None (30 m buffer on roads)."""
    for tid, name, ttype, gtype, coords in targets:
        xy = [local.to_xy(*c) for c in coords]
        if gtype == "LineString":
            if any(dist_to_segment(x, y, xy[i], xy[i + 1]) <= 30 for i in range(len(xy) - 1)):
                return tid
        elif point_in_poly(x, y, xy):
            return tid
    return None


def classify(speed):
    if speed < CLASS_CUTS[0]:
        return "stable"
    if speed < CLASS_CUTS[1]:
        return "slow"
    if speed < CLASS_CUTS[2]:
        return "active"
    return "fast"


def main():
    rng = random.Random(SEED)
    aoi = json.loads(AOI_PATH.read_text())
    bbox = aoi["bbox"]
    local = Local(bbox)
    OUT.mkdir(parents=True, exist_ok=True)
    FRAMES.mkdir(parents=True, exist_ok=True)

    xmin, ymin = local.to_xy(bbox["west"], bbox["south"])
    xmax, ymax = local.to_xy(bbox["east"], bbox["north"])

    targets = make_targets(local, bbox)
    tnames = {t[0]: t[1] for t in targets}
    t_hits = {t[0]: [] for t in targets}
    road_xy = [local.to_xy(*c) for c in targets[0][4]]

    def road_x_at(y):
        for (x1, y1), (x2, y2) in zip(road_xy, road_xy[1:]):
            if min(y1, y2) <= y <= max(y1, y2):
                return x1 + (x2 - x1) * (y - y1) / (y2 - y1)
        return road_xy[-1][0]

    # --- dunes ---
    n_dunes = 36
    k_flux = 45.0  # fake bulk flux, m^2/yr, so speed ~ k / height (c ~ Q/H)
    dunes_2025, dunes_2000, props_list = [], [], []
    for i in range(n_dunes):
        did = f"D{i + 1:03d}"
        height = round(rng.uniform(3.0, 22.0), 1)
        heading = round((RDD_DEG + rng.gauss(0, 12)) % 360, 1)
        tracked = rng.random() > 0.2
        if i % 9 == 0:
            speed_med = round(rng.uniform(0.2, 0.9), 2)  # a few near-stable dunes
        else:
            speed_med = round(max(0.3, k_flux / height * rng.uniform(0.8, 1.25)), 2)
        unc = round(rng.uniform(0.4, 0.9) * (1.0 if tracked else 1.8), 2)
        speed_lo = round(max(0.0, speed_med - unc), 2)
        speed_hi = round(speed_med + unc, 2)
        confidence = ("high" if unc < 0.6 else "medium") if tracked else "low"
        length = 60 + height * 14  # m, bigger dunes are longer
        a, b = length / 2, length * 0.38

        # 2025 centre inside the inner part of the AOI (west/north side, upwind of targets)
        # every 4th dune sits just upwind (NW) of the fake east road so the threat logic has cases
        ux, uy = heading_vec(heading)
        if i % 4 == 1:
            gap = max(40.0, speed_hi * rng.uniform(8, 45))  # metres of open sand between leading edge and the road
            cy = rng.uniform(ymin + 0.72 * (ymax - ymin), ymax - 0.10 * (ymax - ymin))
            travel = gap + 30 + a * 0.8  # 30 m road buffer
            cx = road_x_at(cy + uy * travel) - ux * travel
        else:
            while True:  # resample until the dune does not sit on a target
                cx = rng.uniform(xmin + 0.08 * (xmax - xmin), xmax - 0.35 * (xmax - xmin))
                cy = rng.uniform(ymin + 0.25 * (ymax - ymin), ymax - 0.08 * (ymax - ymin))
                if not any(target_hit(local, targets, cx + ux * a * f, cy + uy * a * f) for f in (-1.2, 0, 1.2)):
                    break
        shift = speed_med * (BASE_YEAR - DUNES_START_YEAR)
        cx0, cy0 = cx - ux * shift, cy - uy * shift

        # ray-march from the leading edge along the heading
        lead_x, lead_y = cx + ux * a * 0.8, cy + uy * a * 0.8
        hit_id, hit_dist = None, None
        max_d = max(speed_hi, 0.01) * (HORIZON - BASE_YEAR)
        d = 0.0
        while d <= max_d:
            tid = target_hit(local, targets, lead_x + ux * d, lead_y + uy * d)
            if tid:
                hit_id, hit_dist = tid, round(d, 0)
                break
            d += 10.0
        reach_min = reach_max = None
        if hit_id is not None:
            y_fast = BASE_YEAR + hit_dist / speed_hi
            y_med = BASE_YEAR + hit_dist / speed_med
            reach_min = int(math.floor(y_fast)) if y_fast <= HORIZON else None
            reach_max = int(math.ceil(y_med)) if y_med <= HORIZON else None
            if reach_min is None:
                hit_id, hit_dist = None, None
        threat = reach_min is not None and reach_min <= PROJECTION_END
        if hit_id:
            t_hits[hit_id].append((reach_min, reach_max))

        props = {
            "id": did,
            "height_m": height,
            "area_km2": round(math.pi * a * b * 0.9 / 1e6, 4),
            "speed_med_myr": speed_med,
            "speed_lo_myr": speed_lo,
            "speed_hi_myr": speed_hi,
            "heading_deg": heading,
            "uncertainty_myr": unc,
            "confidence": confidence,
            "speed_source": "tracked" if tracked else "height_model",
            "class": classify(speed_med),
            "threat": threat,
            "nearest_target": tnames[hit_id] if hit_id else None,
            "distance_to_target_m": hit_dist,
            "reach_year_min": reach_min,
            "reach_year_max": reach_max,
            "wind_agreement_deg": round(ang_diff(heading, RDD_DEG), 1),
        }
        props_list.append(props)
        ring25 = [list(local.to_ll(*p)) for p in ellipse_ring(cx, cy, a, b, heading)]
        ring00 = [list(local.to_ll(*p)) for p in ellipse_ring(cx0, cy0, a, b, heading)]
        dunes_2025.append({"type": "Feature", "properties": props, "geometry": {"type": "Polygon", "coordinates": [ring25]}})
        dunes_2000.append({"type": "Feature", "properties": {"id": did, "year": DUNES_START_YEAR},
                           "geometry": {"type": "Polygon", "coordinates": [ring00]}})

    def fc(features, note):
        return {"type": "FeatureCollection", "placeholder": True, "note": note, "features": features}

    write_json(OUT / "dunes.geojson", fc(dunes_2025, PLACEHOLDER_NOTE + " 2025 positions."))
    write_json(OUT / "dunes_2000.geojson", fc(dunes_2000, PLACEHOLDER_NOTE + " Year-2000 positions, same IDs as dunes.geojson."))

    # --- vectors (thinned grid) ---
    vecs = []
    nx, ny = 12, 12
    for j in range(ny):
        for i in range(nx):
            x = xmin + (i + 0.5) / nx * (xmax - xmin)
            y = ymin + (j + 0.5) / ny * (ymax - ymin)
            sp = round(max(0.1, rng.lognormvariate(math.log(3.5), 0.45)), 2)
            vecs.append({"type": "Feature",
                         "properties": {"speed_myr": sp, "heading_deg": round((RDD_DEG + rng.gauss(0, 15)) % 360, 1),
                                        "quality": round(rng.uniform(0.3, 1.0), 2)},
                         "geometry": {"type": "Point", "coordinates": list(local.to_ll(x, y))}})
    write_json(OUT / "vectors.geojson", fc(vecs, PLACEHOLDER_NOTE + " Thinned motion grid."))

    # --- targets ---
    tfeat = []
    for tid, name, ttype, gtype, coords in targets:
        hits = t_hits[tid]
        mins = [h[0] for h in hits if h[0] is not None]
        maxs = [h[1] for h in hits if h[1] is not None]
        geom = {"type": gtype, "coordinates": [list(c) for c in coords] if gtype == "LineString" else [[list(c) for c in coords]]}
        tfeat.append({"type": "Feature",
                      "properties": {"id": tid, "name": name, "type": ttype,
                                     "hit_year_min": min(mins) if mins else None,
                                     "hit_year_max": max(maxs) if maxs else None},
                      "geometry": geom})
    write_json(OUT / "targets.geojson", fc(tfeat, PLACEHOLDER_NOTE + " Fake roads/farms, not OpenStreetMap data."))

    # --- frames + manifest ---
    obs_years = [(2001, "Landsat 7 ETM+ B8", "L7"), (2013, "Landsat 8 OLI B8", "L8"),
                 (2019, "Landsat 8 OLI B8", "L8"), (2025, "Landsat 9 OLI-2 B8", "L9")]
    prj_years = [2030, 2040, 2050]
    observed, prj_med, prj_fast = [], [], []
    for yr, sensor, tag in obs_years:
        f = f"frames/obs_{yr}.png"
        write_png(OUT / f, 64, 64, frame_pixel((57, 208, 255), 120))
        observed.append({"year": yr, "date": f"{yr}-05-01", "scene_id": f"PLACEHOLDER_{tag}_{yr}",
                         "sensor": sensor, "pixel_m": 15, "file": f})
    for yr in prj_years:
        fm, ff = f"frames/prj_med_{yr}.png", f"frames/prj_fast_{yr}.png"
        write_png(OUT / fm, 64, 64, frame_pixel((240, 180, 41), 110))
        write_png(OUT / ff, 64, 64, frame_pixel((248, 81, 73), 90))
        prj_med.append({"year": yr, "file": fm})
        prj_fast.append({"year": yr, "file": ff})
    write_json(FRAMES / "manifest.json", {
        "placeholder": True,
        "note": PLACEHOLDER_NOTE + " Frames are blank transparent PNGs; dates and scene IDs are fake.",
        "bounds": {k: bbox[k] for k in ("west", "south", "east", "north")},
        "observed": observed, "projected_median": prj_med, "projected_fast": prj_fast,
    })

    # --- wind ---
    yearly, totals_e, totals_n, dp_total = [], 0.0, 0.0, 0.0
    for yr in range(2000, 2025):
        dp = round(rng.uniform(220, 420), 1)
        rdd = round((RDD_DEG + rng.gauss(0, 8)) % 360, 1)
        rdp = round(dp * rng.uniform(0.5, 0.75), 1)
        yearly.append({"year": yr, "DP": dp, "RDP": rdp, "RDD_deg": rdd})
        ex, ny_ = heading_vec(rdd)
        totals_e += rdp * ex
        totals_n += rdp * ny_
        dp_total += dp
    n_years = len(yearly)
    DP = round(dp_total / n_years, 1)
    RDP = round(math.hypot(totals_e, totals_n) / n_years, 1)
    RDD = round(math.degrees(math.atan2(totals_e, totals_n)) % 360, 1)
    rose = []
    for k in range(16):
        sec = k * 22.5
        w_ = math.exp(-((ang_diff(sec, RDD_DEG) / 35.0) ** 2))
        rose.append({"sector_deg": sec, "dp": round(DP * (0.04 + 0.5 * w_) / 2.2, 1)})
    lat_c = round((bbox["south"] + bbox["north"]) / 2, 4)
    lon_c = round((bbox["west"] + bbox["east"]) / 2, 4)
    write_json(OUT / "wind_summary.json", {
        "placeholder": True,
        "note": PLACEHOLDER_NOTE + " DP/RDP are mean annual values in vector units; sand_rose sectors are downwind direction.",
        "location": {"lat": lat_c, "lon": lon_c}, "period": "2000-2024", "source": "NASA MERRA-2 U10M/V10M hourly",
        "threshold_kt": 12, "DP": DP, "RDP": RDP, "RDD_deg": RDD, "RDP_DP": round(RDP / DP, 2),
        "dp_class": "low" if DP < 200 else ("intermediate" if DP < 400 else "high"),
        "yearly": yearly, "sand_rose": rose,
    })

    # --- summary ---
    speeds = sorted(p["speed_med_myr"] for p in props_list)
    counts = {c: sum(1 for p in props_list if p["class"] == c) for c in ("stable", "slow", "active", "fast")}
    write_json(OUT / "summary.json", {
        "placeholder": True,
        "note": PLACEHOLDER_NOTE + " AOI box is unverified (pipeline/aoi.json verified=false).",
        "aoi_name": aoi["name"],
        "aoi_bounds": {k: bbox[k] for k in ("west", "south", "east", "north")},
        "baseline": {"start_date": observed[0]["date"], "end_date": observed[-1]["date"],
                     "years": round(BASE_YEAR - 2001, 2)},
        "n_dunes": len(props_list),
        "counts_by_class": counts,
        "n_threat": sum(1 for p in props_list if p["threat"]),
        "speed_median_myr": round(percentile(speeds, 50), 2),
        "speed_p10_myr": round(percentile(speeds, 10), 2),
        "speed_p90_myr": round(percentile(speeds, 90), 2),
        "uncertainty_myr": round(percentile(sorted(p["uncertainty_myr"] for p in props_list), 50), 2),
        "mean_wind_agreement_deg": round(sum(p["wind_agreement_deg"] for p in props_list) / len(props_list), 1),
        "validation": {
            "published": {"reference": "Fareaa 2025 UAEU thesis", "their_value": "PLACEHOLDER",
                          "our_value": "PLACEHOLDER", "note": "PLACEHOLDER: not yet compared."},
            "second_dataset": {"dataset": "NASA HLS L30/S30", "period": "PLACEHOLDER",
                               "their_value": "PLACEHOLDER", "our_value": "PLACEHOLDER",
                               "note": "PLACEHOLDER: not yet compared."},
        },
        "data_handling": {"scenes_rejected": 0, "cloud_masking": "QA_PIXEL / Fmask", "windows_rejected_pct": 0,
                          "notes": "PLACEHOLDER: no scenes processed yet."},
        "limits": [
            "PLACEHOLDER DATA: none of these numbers are measurements.",
            "The projection is advection along measured motion, assuming 2000-2024 conditions continue.",
            "It does not model dune deformation, merging or splitting.",
            "Vegetation, windbreaks, leveling and climate change alter the outcome.",
            "NASADEM shapes are from 2000 and shifted to 2025.",
            "MERRA-2 is coarse (~0.5 x 0.625 deg).",
            "Results are valid for this dune field and period only.",
        ],
    })

    # --- sources ---
    obs_dates = [o["date"] for o in observed]
    src = lambda **kw: {**kw, "note": "PLACEHOLDER entry: dates are fake; dataset links to be re-checked when real data is used."}
    write_json(OUT / "sources.json", [
        src(name="Landsat 7 ETM+ Collection 2 Level-1", provider="NASA / USGS", used_for="dune motion (B8, 15 m) - PLACEHOLDER",
            dates=obs_dates[:1], place="PLACEHOLDER AOI (unverified)", pixel="15 m",
            link="https://www.usgs.gov/landsat-missions/landsat-collection-2-level-1-data", doi="https://doi.org/10.5066/P9TU80IG"),
        src(name="Landsat 8-9 OLI/TIRS Collection 2 Level-1", provider="NASA / USGS", used_for="dune motion (B8, 15 m) - PLACEHOLDER",
            dates=obs_dates[1:], place="PLACEHOLDER AOI (unverified)", pixel="15 m",
            link="https://www.usgs.gov/landsat-missions/landsat-collection-2-level-1-data", doi="https://doi.org/10.5066/P975CC9B"),
        src(name="Harmonized Landsat Sentinel-2 (HLSL30/HLSS30) v2.0", provider="NASA LP DAAC", used_for="second-dataset check - PLACEHOLDER",
            dates=[], place="PLACEHOLDER AOI (unverified)", pixel="30 m",
            link="https://lpdaac.usgs.gov/products/hlsl30v002/", doi="https://doi.org/10.5067/HLS/HLSL30.002"),
        src(name="MERRA-2 tavg1_2d_slv_Nx (U10M, V10M)", provider="NASA GMAO / GES DISC", used_for="wind drift potential - PLACEHOLDER",
            dates=["2000-01-01/2024-12-31"], place="PLACEHOLDER AOI centroid", pixel="0.5 x 0.625 deg",
            link="https://disc.gsfc.nasa.gov/datasets/M2T1NXSLV_5.12.4/summary", doi="https://doi.org/10.5067/VJAFPLI1CSIV"),
        src(name="NASADEM Merged DEM Global 1 arc second", provider="NASA JPL / LP DAAC", used_for="dune outlines and heights - PLACEHOLDER",
            dates=["2000-02"], place="PLACEHOLDER AOI (unverified)", pixel="30 m",
            link="https://lpdaac.usgs.gov/products/nasadem_hgtv001/", doi="https://doi.org/10.5067/MEaSUREs/NASADEM/NASADEM_HGT.001"),
    ])

    print(f"Wrote placeholders for AOI '{aoi['name']}' to {OUT}")
    print(f"  dunes: {len(props_list)}  classes: {counts}  threat: {sum(1 for p in props_list if p['threat'])}")


def percentile(sorted_vals, q):
    if not sorted_vals:
        return 0.0
    pos = (len(sorted_vals) - 1) * q / 100
    lo, hi = math.floor(pos), math.ceil(pos)
    return sorted_vals[lo] + (sorted_vals[hi] - sorted_vals[lo]) * (pos - lo)


def write_json(path, obj):
    path.write_text(json.dumps(obj, indent=1, allow_nan=False) + "\n")


if __name__ == "__main__":
    main()
